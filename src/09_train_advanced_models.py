def select_threshold_by_f1(y_true, y_proba, step=0.01):
    """
    Sweep thresholds from 0.05 to 0.95 and return the one that maximises F1.
    This is run on the VALIDATION set only — never on Cohort B.
    """
    best_thresh = 0.5
    best_f1 = 0.0
    thresholds = np.arange(0.05, 0.96, step)
    for t in thresholds:
        y_pred = (y_proba >= t).astype(int)
        f1 = f1_score(y_true, y_pred, zero_division=0)
        if f1 > best_f1:
            best_f1 = f1
            best_thresh = t
    return round(float(best_thresh), 4), round(float(best_f1), 6)


def compute_metrics(y_true, y_proba, threshold, label=""):
    """Return a dict of all reported metrics at a given threshold."""
    y_pred = (y_proba >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
    return {
        "label"         : label,
        "threshold"     : float(threshold),
        "roc_auc"       : round(float(roc_auc_score(y_true, y_proba)), 6),
        "pr_auc"        : round(float(average_precision_score(y_true, y_proba)), 6),
        "f1"            : round(float(f1_score(y_true, y_pred, zero_division=0)), 6),
        "precision"     : round(float(precision_score(y_true, y_pred, zero_division=0)), 6),
        "recall"        : round(float(recall_score(y_true, y_pred, zero_division=0)), 6),
        "confusion_matrix": {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp)},
    }

